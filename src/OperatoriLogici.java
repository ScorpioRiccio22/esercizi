
public class OperatoriLogici {

	public static void main(String[] args) {
		int x = 10; 

        if (x < 10 || x > 20) {
            System.out.println("Il numero " + x + " non è compreso tra 10 e 20.");
        } else {
            System.out.println("Il numero " + x + " è compreso tra 10 e 20.");
        }
	}

}
